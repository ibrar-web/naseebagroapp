/**
 * Builds src/services/crashReporter/screenModules.ts from AppNavigator.tsx:
 * route name → app module and screen file, so crash reports say where a
 * crash happened even in release builds (where stack traces are minified).
 *
 * Run after adding or moving a screen:  npm run crash:screens
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const navFile = path.join(root, 'src/navigation/AppNavigator.tsx');
const outFile = path.join(root, 'src/services/crashReporter/screenModules.ts');
const source = fs.readFileSync(navFile, 'utf8');

// import DealDetail from '../app/deals/screens/DealDetail';
const imports = {};
for (const m of source.matchAll(/^import (\w+) from '\.\.\/app\/([^']+)';/gm)) {
  imports[m[1]] = m[2];
}

// <Stack.Screen name="DealDetail" component={DealDetail} />
const entries = [];
for (const m of source.matchAll(/name="(\w+)"\s+component=\{(\w+)\}/g)) {
  const [, route, component] = m;
  const importPath = imports[component];
  if (!importPath) continue;
  const file = fs.existsSync(path.join(root, 'src/app', `${importPath}.tsx`))
    ? `src/app/${importPath}.tsx`
    : `src/app/${importPath}`;
  entries.push([route, importPath.split('/')[0], file]);
}

const body = entries
  .map(([route, module, file]) => `  ${route}: { module: '${module}', file: '${file}' },`)
  .join('\n');

fs.writeFileSync(
  outFile,
  `// Generated by scripts/generate-screen-modules.js — do not edit by hand.
// Route name → app module and screen file, used in crash reports.

export const SCREEN_MODULES: Record<string, { module: string; file: string }> = {
${body}
};
`,
);
console.log(`Wrote ${entries.length} screens to ${path.relative(root, outFile)}`);
